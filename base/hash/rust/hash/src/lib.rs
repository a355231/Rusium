//! Rust port of `base/hash/hash.{h,cc}`, together with the two third-party
//! hash functions it calls: SuperFastHash (base/third_party/superfasthash)
//! and CityHash (base/third_party/cityhash, version 1.1.1 namespace).
//!
//! Functions:
//! - [`persistent_hash`] (and the deprecated [`deprecated_hash`]): SuperFastHash
//!   32-bit output. The value must never change, because it is meant to be
//!   stored on disk or sent over the network.
//! - [`fast_hash`]: CityHash, 64-bit on 64-bit targets and 32-bit otherwise.
//!   Its output may change between versions.
//! - [`hash_ints32`], [`hash_ints64`], [`hash_ints`]: combine two integers.
//! - [`int_pair_hash`] (C++ `IntPairHash`) and [`hash_combine`] (C++
//!   `HashCombine`).
//!
//! Results are bit-exact with the C++ code in a release build. The
//! known-answer tests were generated by compiling the C++ sources. On a 64-bit
//! target, the tests run the 64-bit paths. The 32-bit `size_t` paths are
//! checked by testing `city_hash32` and `fold_to_32_bits` directly. The C++
//! code returns `size_t`, so the Rust functions return `usize`.
//!
//! Differences from the C++ version:
//! - `DCHECK_IS_ON()` builds of C++ mix a per-process address into
//!   [`fast_hash`] and the `HashInts*` functions, so their output varies
//!   between runs. That mixing is not ported. This crate always matches the
//!   release-build output.
//! - `persistent_hash` panics for inputs longer than `i32::MAX` bytes. The C++
//!   code calls `NOTREACHED()` and then `checked_cast<int>`, which crash in the
//!   same way.
//! - `hash_combine` uses `std::hash`-style hashing through Rust's `Hash` trait
//!   and `DefaultHasher`. Its values differ from C++ `std::hash`, and they may
//!   change between Rust releases. Do not persist them. The same goes for
//!   `int_pair_hash`, which hashes its integers with `hash_ints`, which is
//!   stable.
//! - The C++ variadic `HashCombine(seed, a, b, ...)` is a chain of
//!   single-value calls. Call `hash_combine` repeatedly instead.
//! - `CityHash64WithSeed`, `CityHash64WithSeeds` and the `CityHash128`
//!   functions are not ported, because `base/hash` does not use them.
//! - `hash_perftest.cc`, `legacy_hash` and `sha1` are outside this unit and
//!   are not ported.

#![forbid(unsafe_code)]

use std::collections::hash_map::DefaultHasher;
use std::hash::{Hash, Hasher};

// ---------------------------------------------------------------------------
// SuperFastHash (Paul Hsieh, 2010), as used by base::PersistentHash.
// ---------------------------------------------------------------------------

/// Reads the 16-bit little-endian value at `data[offset..]`, as `get16bits`
/// in superfasthash.c does.
fn get16bits(data: &[u8], offset: usize) -> u32 {
    (u32::from(data[offset + 1]) << 8) + u32::from(data[offset])
}

/// Computes SuperFastHash over `data`. `data.len()` must be at most
/// `i32::MAX`, because the C function takes an `int` length.
fn super_fast_hash(data: &[u8]) -> u32 {
    let len = data.len();
    if len == 0 {
        return 0;
    }
    let mut hash = len as u32;

    let mut chunks = data.chunks_exact(4);
    for chunk in chunks.by_ref() {
        hash = hash.wrapping_add(get16bits(chunk, 0));
        let tmp = (get16bits(chunk, 2) << 11) ^ hash;
        hash = (hash << 16) ^ tmp;
        hash = hash.wrapping_add(hash >> 11);
    }

    // Handle the end cases. Note that the trailing bytes are sign-extended
    // (`(signed char)` in the C code), so bytes >= 0x80 contribute their
    // two's-complement value.
    let rem = chunks.remainder();
    match rem.len() {
        3 => {
            hash = hash.wrapping_add(get16bits(rem, 0));
            hash ^= hash << 16;
            hash ^= (i32::from(rem[2] as i8) as u32) << 18;
            hash = hash.wrapping_add(hash >> 11);
        }
        2 => {
            hash = hash.wrapping_add(get16bits(rem, 0));
            hash ^= hash << 11;
            hash = hash.wrapping_add(hash >> 17);
        }
        1 => {
            hash = hash.wrapping_add(i32::from(rem[0] as i8) as u32);
            hash ^= hash << 10;
            hash = hash.wrapping_add(hash >> 1);
        }
        _ => {}
    }

    // Force avalanching of the final bits.
    hash ^= hash << 3;
    hash = hash.wrapping_add(hash >> 5);
    hash ^= hash << 4;
    hash = hash.wrapping_add(hash >> 17);
    hash ^= hash << 25;
    hash = hash.wrapping_add(hash >> 6);
    hash
}

