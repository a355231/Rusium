/// Largest input that `persistent_hash` accepts, the C `int` length limit.
const MAX_PERSISTENT_HASH_LEN: usize = i32::MAX as usize;

/// Computes the persistent 32-bit hash of `data` (base::PersistentHash).
///
/// The output is a stable function of the bytes and will not change, so it
/// can be stored or sent to other machines. Empty input hashes to 0.
///
/// # Panics
///
/// Panics if `data` is longer than `i32::MAX` bytes. The C++ code also fails.
///
/// # Examples
///
/// ```
/// use hash::persistent_hash;
/// assert_eq!(persistent_hash(b""), 0);
/// assert_eq!(persistent_hash("hello world"), 2794219650);
/// ```
pub fn persistent_hash(data: impl AsRef<[u8]>) -> u32 {
    let data = data.as_ref();
    assert!(
        data.len() <= MAX_PERSISTENT_HASH_LEN,
        "persistent_hash input longer than i32::MAX bytes"
    );
    super_fast_hash(data)
}

/// The deprecated `base::Hash(const std::string&)`. Same value as
/// [`persistent_hash`]. Prefer `persistent_hash` for new code.
pub fn deprecated_hash(data: impl AsRef<[u8]>) -> u32 {
    persistent_hash(data)
}

/// Computes the fast in-process hash (base::FastHash) with CityHash, 64-bit on
/// 64-bit targets and 32-bit otherwise. The output may change between
/// releases, so do not persist it.
pub fn fast_hash(data: impl AsRef<[u8]>) -> usize {
    let data = data.as_ref();
    if usize::BITS > 32 {
        city_hash64(data) as usize
    } else {
        city_hash32(data) as usize
    }
}

/// Folds a 64-bit hash to 32 bits with multiply-add hashing, as in the C++
/// `HashInts32Impl`/`HashInts64Impl` when `size_t` is 32 bits.
fn fold_to_32_bits(hash64: u64, odd_random: u64, shift_random: u32) -> usize {
    let mixed = hash64.wrapping_mul(odd_random).wrapping_add(u64::from(shift_random));
    (mixed >> 32) as usize
}

/// Hashes two 32-bit integers (base::HashInts32).
pub fn hash_ints32(value1: u32, value2: u32) -> usize {
    let hash64 = (u64::from(value1) << 32) | u64::from(value2);
    if usize::BITS > 32 {
        return hash64 as usize;
    }
    let odd_random = (481_046_412u64 << 32) | 1_025_306_955u64;
    let shift_random = 10_121u32 << 16;
    fold_to_32_bits(hash64, odd_random, shift_random)
}

/// Hashes two 64-bit integers (base::HashInts64).
pub fn hash_ints64(value1: u64, value2: u64) -> usize {
    // Compound integer hash over the four 32-bit halves.
    let value1a = value1 & 0xffff_ffff;
    let value1b = (value1 >> 32) & 0xffff_ffff;
    let value2a = value2 & 0xffff_ffff;
    let value2b = (value2 >> 32) & 0xffff_ffff;
    let hash64 = value1a
        .wrapping_mul(842_304_669)
        .wrapping_add(value1b.wrapping_mul(619_063_811))
        .wrapping_add(value2a.wrapping_mul(937_041_849))
        .wrapping_add(value2b.wrapping_mul(3_309_708_029));
    if usize::BITS > 32 {
        return hash64 as usize;
    }
    let odd_random = (1_578_233_944u64 << 32) | 194_370_989u64;
    let shift_random = 20_591u32 << 16;
    fold_to_32_bits(hash64, odd_random, shift_random)
}

/// An integer type that [`hash_ints`] accepts. It mirrors the C++ template,
/// which uses the 64-bit hash when either argument is wider than 32 bits.
pub trait HashInt: Copy {
    /// The value sign-extended (for signed types) to 64 bits, as C++
    /// `static_cast<uint64_t>` does.
    fn hash_bits(self) -> u64;
    /// The size of the type in bytes.
    fn byte_size(self) -> usize;
}

macro_rules! impl_hash_int {
    ($($ty:ty),* $(,)?) => {
        $(
            impl HashInt for $ty {
                fn hash_bits(self) -> u64 {
                    self as u64
                }
                fn byte_size(self) -> usize {
                    std::mem::size_of::<$ty>()
                }
            }
        )*
    };
}

impl_hash_int!(u8, u16, u32, u64, usize, i8, i16, i32, i64, isize);

/// Hashes a pair of integers (base::HashInts). The result is the 32-bit hash
/// when both arguments are at most 32 bits wide, and the 64-bit hash otherwise.
pub fn hash_ints<T1: HashInt, T2: HashInt>(value1: T1, value2: T2) -> usize {
    if value1.byte_size() > 4 || value2.byte_size() > 4 {
        hash_ints64(value1.hash_bits(), value2.hash_bits())
    } else {
        hash_ints32(value1.hash_bits() as u32, value2.hash_bits() as u32)
    }
}

/// Hashes an integer pair for use as a map key (base::IntPairHash).
pub fn int_pair_hash<T1: HashInt, T2: HashInt>(pair: (T1, T2)) -> usize {
    hash_ints(pair.0, pair.1)
}

/// Combines `seed` with the hash of `value` (base::HashCombine). The `Hash`
/// trait plays the role of `std::hash`. Values differ from C++ and may change
/// between Rust releases, so do not persist them.
pub fn hash_combine<T: Hash + ?Sized>(seed: usize, value: &T) -> usize {
    let mut hasher = DefaultHasher::new();
    value.hash(&mut hasher);
    let value_hash = hasher.finish() as usize;
    if usize::BITS > 32 {
        hash_ints64(seed as u64, value_hash as u64)
    } else {
        hash_ints32(seed as u32, value_hash as u32)
    }
}

