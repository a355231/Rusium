        // Mixed widths use the 64-bit hash, so a small value and a wide value
        // differ from the 32-bit hash of the same pair.
        assert_eq!(hash_ints(1u8, 2u16), hash_ints32(1, 2));
        assert_eq!(hash_ints(1u32, 2u64), hash_ints64(1, 2));
        // Negative values are sign-extended in the 64-bit path, and truncated
        // in the 32-bit path.
        assert_eq!(hash_ints(-1i32, 0i32), hash_ints32(0xffff_ffff, 0));
