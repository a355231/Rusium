const K0: u64 = 0xc3a5_c85c_97cb_3127;
const K1: u64 = 0xb492_b66f_be98_f273;
const K2: u64 = 0x9ae1_6a3b_2f90_404f;
const C1: u32 = 0xcc9e_2d51;
const C2: u32 = 0x1b87_3593;
const KMUL: u64 = 0x9ddf_ea08_eb38_2d69;

/// Little-endian 64-bit load at `s[at..]`, as `Fetch64`.
fn fetch64(s: &[u8], at: usize) -> u64 {
    u64::from_le_bytes(s[at..at + 8].try_into().expect("8 bytes"))
}

/// Little-endian 32-bit load at `s[at..]`, as `Fetch32`.
fn fetch32(s: &[u8], at: usize) -> u32 {
    u32::from_le_bytes(s[at..at + 4].try_into().expect("4 bytes"))
}

fn fmix(mut h: u32) -> u32 {
    h ^= h >> 16;
    h = h.wrapping_mul(0x85eb_ca6b);
    h ^= h >> 13;
    h = h.wrapping_mul(0xc2b2_ae35);
    h ^= h >> 16;
    h
}

fn rotate32(val: u32, shift: u32) -> u32 {
    val.rotate_right(shift)
}

fn mur(a: u32, h: u32) -> u32 {
    let a = rotate32(a.wrapping_mul(C1), 17).wrapping_mul(C2);
    let h = rotate32(h ^ a, 19);
    h.wrapping_mul(5).wrapping_add(0xe654_6b64)
}

fn hash32_len13to24(s: &[u8], len: usize) -> u32 {
    let a = fetch32(s, len / 2 - 4);
    let b = fetch32(s, 4);
    let c = fetch32(s, len - 8);
    let d = fetch32(s, len / 2);
    let e = fetch32(s, 0);
    let f = fetch32(s, len - 4);
    let h = len as u32;
    fmix(mur(f, mur(e, mur(d, mur(c, mur(b, mur(a, h)))))))
}

fn hash32_len0to4(s: &[u8], len: usize) -> u32 {
    let mut b: u32 = 0;
    let mut c: u32 = 9;
    for &byte in &s[..len] {
        // `signed char` in the C code, so sign-extended.
        let v = i32::from(byte as i8) as u32;
        b = b.wrapping_mul(C1).wrapping_add(v);
        c ^= b;
    }
    fmix(mur(b, mur(len as u32, c)))
}

fn hash32_len5to12(s: &[u8], len: usize) -> u32 {
    let a = (len as u32).wrapping_add(fetch32(s, 0));
    let b = (len as u32).wrapping_mul(5).wrapping_add(fetch32(s, len - 4));
    let c = 9u32.wrapping_add(fetch32(s, (len >> 1) & 4));
    let d = (len as u32).wrapping_mul(5);
    fmix(mur(c, mur(b, mur(a, d))))
}

/// CityHash32 (base::internal::cityhash_v111::CityHash32).
fn city_hash32(s: &[u8]) -> u32 {
    let len = s.len();
    if len <= 24 {
        return if len <= 12 {
            if len <= 4 {
                hash32_len0to4(s, len)
            } else {
                hash32_len5to12(s, len)
            }
        } else {
            hash32_len13to24(s, len)
        };
    }

    // len > 24
    let mut h = len as u32;
    let mut g = C1.wrapping_mul(h);
    let mut f = g;
    let mut a0 = rotate32(fetch32(s, len - 4).wrapping_mul(C1), 17).wrapping_mul(C2);
    let a1 = rotate32(fetch32(s, len - 8).wrapping_mul(C1), 17).wrapping_mul(C2);
    let a2 = rotate32(fetch32(s, len - 16).wrapping_mul(C1), 17).wrapping_mul(C2);
    let a3 = rotate32(fetch32(s, len - 12).wrapping_mul(C1), 17).wrapping_mul(C2);
    let a4 = rotate32(fetch32(s, len - 20).wrapping_mul(C1), 17).wrapping_mul(C2);
    h ^= a0;
    h = rotate32(h, 19).wrapping_mul(5).wrapping_add(0xe654_6b64);
    h ^= a2;
    h = rotate32(h, 19).wrapping_mul(5).wrapping_add(0xe654_6b64);
    g ^= a1;
    g = rotate32(g, 19).wrapping_mul(5).wrapping_add(0xe654_6b64);
    g ^= a3;
    g = rotate32(g, 19).wrapping_mul(5).wrapping_add(0xe654_6b64);
    f = f.wrapping_add(a4);
    f = rotate32(f, 19).wrapping_mul(5).wrapping_add(0xe654_6b64);

    let mut iters = (len - 1) / 20;
    let mut pos = 0;
    loop {
        a0 = rotate32(fetch32(s, pos).wrapping_mul(C1), 17).wrapping_mul(C2);
        let a1 = fetch32(s, pos + 4);
        let a2 = rotate32(fetch32(s, pos + 8).wrapping_mul(C1), 17).wrapping_mul(C2);
        let a3 = rotate32(fetch32(s, pos + 12).wrapping_mul(C1), 17).wrapping_mul(C2);
        let a4 = fetch32(s, pos + 16);
        h ^= a0;
        h = rotate32(h, 18).wrapping_mul(5).wrapping_add(0xe654_6b64);
        f = f.wrapping_add(a1);
        f = rotate32(f, 19).wrapping_mul(C1);
        g = g.wrapping_add(a2);
        g = rotate32(g, 18).wrapping_mul(5).wrapping_add(0xe654_6b64);
        h ^= a3.wrapping_add(a1);
        h = rotate32(h, 19).wrapping_mul(5).wrapping_add(0xe654_6b64);
        g ^= a4;
        g = g.swap_bytes().wrapping_mul(5);
        h = h.wrapping_add(a4.wrapping_mul(5));
        h = h.swap_bytes();
        f = f.wrapping_add(a0);
        // PERMUTE3(f, h, g) in the C code: f <- g, h <- f, g <- h.
        (f, h, g) = (g, f, h);
        pos += 20;
        iters -= 1;
        if iters == 0 {
            break;
        }
    }
    g = rotate32(g, 11).wrapping_mul(C1);
    g = rotate32(g, 17).wrapping_mul(C1);
    f = rotate32(f, 11).wrapping_mul(C1);
    f = rotate32(f, 17).wrapping_mul(C1);
    h = rotate32(h.wrapping_add(g), 19).wrapping_mul(5).wrapping_add(0xe654_6b64);
    h = rotate32(h, 17).wrapping_mul(C1);
    h = rotate32(h.wrapping_add(f), 19).wrapping_mul(5).wrapping_add(0xe654_6b64);
    h = rotate32(h, 17).wrapping_mul(C1);
    h
}

fn rotate64(val: u64, shift: u32) -> u64 {
    val.rotate_right(shift)
}

fn shift_mix(val: u64) -> u64 {
    val ^ (val >> 47)
}

/// Hash128to64 (Murmur-inspired), as `HashLen16(u, v)`.
fn hash_len16(u: u64, v: u64) -> u64 {
    let mut a = (u ^ v).wrapping_mul(KMUL);
    a ^= a >> 47;
    let mut b = (v ^ a).wrapping_mul(KMUL);
    b ^= b >> 47;
    b.wrapping_mul(KMUL)
}

/// `HashLen16(u, v, mul)` in the C code.
fn hash_len16_mul(u: u64, v: u64, mul: u64) -> u64 {
    let mut a = (u ^ v).wrapping_mul(mul);
    a ^= a >> 47;
    let mut b = (v ^ a).wrapping_mul(mul);
    b ^= b >> 47;
    b.wrapping_mul(mul)
}

fn hash_len0to16(s: &[u8], len: usize) -> u64 {
    if len >= 8 {
        let mul = K2.wrapping_add((len as u64).wrapping_mul(2));
        let a = fetch64(s, 0).wrapping_add(K2);
        let b = fetch64(s, len - 8);
        let c = rotate64(b, 37).wrapping_mul(mul).wrapping_add(a);
        let d = rotate64(a, 25).wrapping_add(b).wrapping_mul(mul);
        return hash_len16_mul(c, d, mul);
    }
    if len >= 4 {
        let mul = K2.wrapping_add((len as u64).wrapping_mul(2));
        let a = u64::from(fetch32(s, 0));
        return hash_len16_mul(
            (len as u64).wrapping_add(a << 3),
            u64::from(fetch32(s, len - 4)),
            mul,
        );
    }
    if len > 0 {
        let a = u32::from(s[0]);
        let b = u32::from(s[len >> 1]);
        let c = u32::from(s[len - 1]);
        let y = a.wrapping_add(b << 8);
        let z = (len as u32).wrapping_add(c << 2);
        return shift_mix(u64::from(y).wrapping_mul(K2) ^ u64::from(z).wrapping_mul(K0))
            .wrapping_mul(K2);
    }
    K2
}

fn hash_len17to32(s: &[u8], len: usize) -> u64 {
    let mul = K2.wrapping_add((len as u64).wrapping_mul(2));
    let a = fetch64(s, 0).wrapping_mul(K1);
    let b = fetch64(s, 8);
    let c = fetch64(s, len - 8).wrapping_mul(mul);
    let d = fetch64(s, len - 16).wrapping_mul(K2);
    hash_len16_mul(
        rotate64(a.wrapping_add(b), 43).wrapping_add(rotate64(c, 30)).wrapping_add(d),
        a.wrapping_add(rotate64(b.wrapping_add(K2), 18)).wrapping_add(c),
        mul,
    )
}

/// `WeakHashLen32WithSeeds(w, x, y, z, a, b)` in the C code.
fn weak_hash_len32_with_seeds(w: u64, x: u64, y: u64, z: u64, a: u64, b: u64) -> (u64, u64) {
    let mut a = a.wrapping_add(w);
    let mut b = rotate64(b.wrapping_add(a).wrapping_add(z), 21);
    let c = a;
    a = a.wrapping_add(x);
    a = a.wrapping_add(y);
    b = b.wrapping_add(rotate64(a, 44));
    (a.wrapping_add(z), b.wrapping_add(c))
}

/// `WeakHashLen32WithSeeds(s + at, a, b)` in the C code.
fn weak_hash_len32_with_seeds_at(s: &[u8], at: usize, a: u64, b: u64) -> (u64, u64) {
    weak_hash_len32_with_seeds(
        fetch64(s, at),
        fetch64(s, at + 8),
        fetch64(s, at + 16),
        fetch64(s, at + 24),
        a,
        b,
    )
}

fn hash_len33to64(s: &[u8], len: usize) -> u64 {
    let mul = K2.wrapping_add((len as u64).wrapping_mul(2));
    let a = fetch64(s, 0).wrapping_mul(K2);
    let b = fetch64(s, 8);
    let c = fetch64(s, len - 24);
    let d = fetch64(s, len - 32);
    let e = fetch64(s, 16).wrapping_mul(K2);
    let f = fetch64(s, 24).wrapping_mul(9);
    let g = fetch64(s, len - 8);
    let h = fetch64(s, len - 16).wrapping_mul(mul);
    let u = rotate64(a.wrapping_add(g), 43)
        .wrapping_add(rotate64(b, 30).wrapping_add(c).wrapping_mul(9));
    let v = (a.wrapping_add(g) ^ d).wrapping_add(f).wrapping_add(1);
    let w = (u.wrapping_add(v)).wrapping_mul(mul).swap_bytes().wrapping_add(h);
    let x = rotate64(e.wrapping_add(f), 42).wrapping_add(c);
    let y = (v.wrapping_add(w)).wrapping_mul(mul).swap_bytes().wrapping_add(g).wrapping_mul(mul);
    let z = e.wrapping_add(f).wrapping_add(c);
    let a = (x.wrapping_add(z)).wrapping_mul(mul).wrapping_add(y).swap_bytes().wrapping_add(b);
    let b = shift_mix((z.wrapping_add(a)).wrapping_mul(mul).wrapping_add(d).wrapping_add(h))
        .wrapping_mul(mul);
    b.wrapping_add(x)
}

/// CityHash64 (base::internal::cityhash_v111::CityHash64).
fn city_hash64(s: &[u8]) -> u64 {
    let len = s.len();
    if len <= 32 {
        return if len <= 16 { hash_len0to16(s, len) } else { hash_len17to32(s, len) };
    }
    if len <= 64 {
        return hash_len33to64(s, len);
    }

    // For longer strings, hash the end first, then loop over 64-byte chunks
    // while keeping 56 bytes of state in x, y, z, v and w.
    let mut x = fetch64(s, len - 40);
    let mut y = fetch64(s, len - 16).wrapping_add(fetch64(s, len - 56));
    let mut z = hash_len16(fetch64(s, len - 48).wrapping_add(len as u64), fetch64(s, len - 24));
    let mut v = weak_hash_len32_with_seeds_at(s, len - 64, len as u64, z);
    let mut w = weak_hash_len32_with_seeds_at(s, len - 32, y.wrapping_add(K1), x);
    x = x.wrapping_mul(K1).wrapping_add(fetch64(s, 0));

    // Decrease len to the nearest multiple of 64, and loop over 64-byte chunks.
    let mut remaining = (len - 1) & !63;
    let mut pos = 0;
    loop {
        x = rotate64(x.wrapping_add(y).wrapping_add(v.0).wrapping_add(fetch64(s, pos + 8)), 37)
            .wrapping_mul(K1);
        y = rotate64(y.wrapping_add(v.1).wrapping_add(fetch64(s, pos + 48)), 42).wrapping_mul(K1);
        x ^= w.1;
        y = y.wrapping_add(v.0).wrapping_add(fetch64(s, pos + 40));
        z = rotate64(z.wrapping_add(w.0), 33).wrapping_mul(K1);
        v = weak_hash_len32_with_seeds_at(s, pos, v.1.wrapping_mul(K1), x.wrapping_add(w.0));
        w = weak_hash_len32_with_seeds_at(
            s,
            pos + 32,
            z.wrapping_add(w.1),
            y.wrapping_add(fetch64(s, pos + 16)),
        );
        std::mem::swap(&mut z, &mut x);
        pos += 64;
        remaining -= 64;
        if remaining == 0 {
            break;
        }
    }
    hash_len16(
        hash_len16(v.0, w.0).wrapping_add(shift_mix(y).wrapping_mul(K1)).wrapping_add(z),
        hash_len16(v.1, w.1).wrapping_add(x),
    )
}

