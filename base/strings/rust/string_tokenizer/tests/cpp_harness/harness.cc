// Generates tests/cpp_golden.rs. Build and run from the repository root:
//   g++ -std=c++20 -O1 -Ibase/strings/rust/string_tokenizer/tests/cpp_harness/shim -I. \
//     base/strings/rust/string_tokenizer/tests/cpp_harness/harness.cc -o /tmp/tok_harness
//   /tmp/tok_harness > /tmp/regenerated.rs
// The shim headers are stand-ins: IsAsciiWhitespace is copied verbatim from
// base/strings/string_util.h and the rest are no-op macros.
// Golden-vector generator. Includes the UNMODIFIED
// base/strings/string_tokenizer.h (shims only for check/compiler/string_util).
// Prints a Rust source file with random cases and the C++ results.
#include "base/strings/string_tokenizer.h"

#include <cstdint>
#include <cstdio>
#include <string>

namespace {

uint64_t g_state = 0x243F6A8885A308D3ull;

uint64_t Next() {
  uint64_t x = g_state;
  x ^= x << 13;
  x ^= x >> 7;
  x ^= x << 17;
  g_state = x;
  return x;
}

size_t Below(size_t n) { return static_cast<size_t>(Next() % n); }

std::string RustLit(const std::string& s) {
  std::string out = "\"";
  for (unsigned char c : s) {
    if (c == '"' || c == '\\') {
      out += '\\';
      out += static_cast<char>(c);
    } else if (c >= 0x20 && c < 0x7f) {
      out += static_cast<char>(c);
    } else {
      char buf[8];
      snprintf(buf, sizeof buf, "\\x%02x", c);
      out += buf;
    }
  }
  return out + "\"";
}

std::string Pick(const std::string& alphabet, size_t max_len) {
  size_t len = Below(max_len + 1);
  std::string s;
  for (size_t i = 0; i < len; ++i) {
    s += alphabet[Below(alphabet.size())];
  }
  return s;
}

}  // namespace

int main() {
  // Printable ASCII plus the whitespace controls, quotes and backslash.
  const std::string kInputAlphabet = " ,;ab'\"\\=\t\n\r\v\f";
  const std::string kDelimAlphabet = " ,;=a\t";
  const std::string kQuoteAlphabet = "'\"\\";
  const int kCases = 500;

  printf("// Generated by a C++ golden harness that compiles the unmodified\n");
  printf("// base/strings/string_tokenizer.h (with stand-in check/compiler/\n");
  printf("// string_util headers). Do not edit by hand.\n\n");
  printf("/// One call to get_next(): (result, token_is_delim, begin, end).\n");
  printf("pub type Ev = (bool, bool, usize, usize);\n\n");
  printf("/// A randomized tokenizer case with the C++ results.\n");
  printf("pub struct Case {\n");
  printf("    pub input: &'static str,\n    pub delims: &'static str,\n");
  printf("    pub quotes: &'static str,\n    pub options: u32,\n");
  printf("    pub skip_over: bool,\n    pub run1: &'static [Ev],\n");
  printf("    pub run2: &'static [Ev],\n}\n\n");
  printf("pub const CASES: &[Case] = &[\n");

  for (int c = 0; c < kCases; ++c) {
    std::string input = Pick(kInputAlphabet, 14);
    std::string delims = Pick(kDelimAlphabet, 3);
    std::string quotes = Pick(kQuoteAlphabet, 2);
    int options = static_cast<int>(Below(4));
    bool skip_over = Below(3) == 0;
    auto policy = skip_over ? base::StringTokenizer::WhitespacePolicy::kSkipOver
                            : base::StringTokenizer::WhitespacePolicy::kIncludeInTokens;

    base::StringTokenizer t(input, delims, policy);
    t.set_options(options);
    t.set_quote_chars(quotes);

    std::string run1, run2;
    for (int pass = 0; pass < 2; ++pass) {
      std::string& out = pass == 0 ? run1 : run2;
      if (pass == 1) {
        t.Reset();
      }
      for (int calls = 0; calls < 200; ++calls) {
        bool ok = t.GetNext();
        char buf[96];
        snprintf(buf, sizeof buf, "(%s, %s, %zu, %zu), ", ok ? "true" : "false",
                 t.token_is_delim() ? "true" : "false",
                 static_cast<size_t>(t.token_begin() - input.begin()),
                 static_cast<size_t>(t.token_end() - input.begin()));
        out += buf;
        if (!ok) {
          break;
        }
      }
    }
    printf("    Case {\n");
    printf("        input: %s,\n", RustLit(input).c_str());
    printf("        delims: %s,\n", RustLit(delims).c_str());
    printf("        quotes: %s,\n", RustLit(quotes).c_str());
    printf("        options: %d,\n", options);
    printf("        skip_over: %s,\n", skip_over ? "true" : "false");
    printf("        run1: &[%s],\n", run1.c_str());
    printf("        run2: &[%s],\n", run2.c_str());
    printf("    },\n");
  }
  printf("];\n");
  return 0;
}
