// Generates the tables in strcat/tests/cpp_golden.rs and
// join_string/tests/cpp_golden.rs. Build and run from the repository root
// (C++23 is needed for std::ranges::fold_left):
//   g++ -std=c++23 -O1 -Ibase/strings/rust/strcat/tests/cpp_harness/shim -I. \
//     base/strings/rust/strcat/tests/cpp_harness/harness_sc.cc \
//     base/strings/strcat.cc -o /tmp/sc_harness
//   /tmp/sc_harness > /tmp/regenerated.rs
// The shim headers are stand-ins: checked_cast skips only the range check
// (the generated inputs are in range) and the rest are no-op macros.
// Golden-vector generator for strcat and the join template. Compiles the
// UNMODIFIED base/strings/strcat.cc, strcat_internal.h and
// join_string_internal.h. Prints Rust source with random cases.
#include <cstdint>
#include <cstdio>
#include <span>
#include <string>
#include <string_view>
#include <vector>

#include "base/strings/join_string_internal.h"
#include "base/strings/strcat.h"

namespace {

uint64_t g_state = 0x9E3779B97F4A7C15ull;
uint64_t Next() {
  uint64_t x = g_state;
  x ^= x << 13;
  x ^= x >> 7;
  x ^= x << 17;
  g_state = x;
  return x;
}
size_t Below(size_t n) { return static_cast<size_t>(Next() % n); }

// UTF-8 pool. Non-ASCII text is printed raw, which is valid in Rust source.
const char* kPool8[] = {"", "a", "bc", "\xc3\xa9", "\xe6\x97\xa5\xe6\x9c\xac", " ",
                        "\xf0\x9f\x98\x80", ",", "xyz"};
constexpr size_t kPoolSize = sizeof(kPool8) / sizeof(kPool8[0]);

std::u16string Pool16(size_t i) {
  switch (i) {
    case 0: return u"";
    case 1: return u"a";
    case 2: return u"bc";
    case 3: return u"é";
    case 4: return u"日本";
    case 5: return u" ";
    case 6: return u"\U0001F600";
    case 7: return u",";
    default: return u"xyz";
  }
}

std::string RustLit(const std::string& s) {
  std::string out = "\"";
  for (unsigned char c : s) {
    if (c == '"' || c == '\\') {
      out += '\\';
      out += static_cast<char>(c);
    } else if (c >= 0x20 && c < 0x7f) {
      out += static_cast<char>(c);
    } else if (c >= 0x80) {
      out += static_cast<char>(c);  // Valid UTF-8 from the pool.
    } else {
      char buf[8];
      snprintf(buf, sizeof buf, "\\x%02x", c);
      out += buf;
    }
  }
  return out + "\"";
}

std::string U16Arr(const std::u16string& s) {
  std::string out = "&[";
  for (char16_t c : s) {
    out += std::to_string(static_cast<unsigned>(c)) + ", ";
  }
  return out + "]";
}

}  // namespace

int main() {
  constexpr int kCases = 150;

  printf("// Generated by a C++ golden harness that compiles the unmodified\n");
  printf("// base/strings/strcat.cc and join_string_internal.h. Do not edit.\n\n");
  printf("pub struct Case {\n    pub pieces: &'static [&'static str],\n");
  printf("    pub prefix: &'static str,\n    pub cat: &'static str,\n");
  printf("    pub append: &'static str,\n}\n\n");
  printf("pub const CASES: &[Case] = &[\n");
  std::vector<std::u16string> pieces16_dummy;
  for (int c = 0; c < kCases; ++c) {
    size_t n = Below(6);
    std::vector<std::string_view> pieces;
    std::string prefix = kPool8[Below(kPoolSize)];
    std::string storage;
    std::vector<std::string> owned;
    for (size_t i = 0; i < n; ++i) {
      owned.push_back(kPool8[Below(kPoolSize)]);
    }
    for (auto& s : owned) pieces.push_back(s);

    std::string cat = base::StrCat(std::span<const std::string_view>(pieces));
    std::string dest = prefix;
    base::StrAppend(&dest, std::span<const std::string_view>(pieces));

    printf("    Case {\n        pieces: &[");
    for (auto& s : owned) printf("%s, ", RustLit(s).c_str());
    printf("],\n        prefix: %s,\n", RustLit(prefix).c_str());
    printf("        cat: %s,\n", RustLit(cat).c_str());
    printf("        append: %s,\n    },\n", RustLit(dest).c_str());
  }
  printf("];\n\n");

  printf("pub struct Case16 {\n    pub pieces: &'static [&'static [u16]],\n");
  printf("    pub prefix: &'static [u16],\n    pub cat: &'static [u16],\n");
  printf("    pub append: &'static [u16],\n}\n\n");
  printf("pub const CASES16: &[Case16] = &[\n");
  for (int c = 0; c < kCases; ++c) {
    size_t n = Below(6);
    std::u16string prefix = Pool16(Below(kPoolSize));
    std::vector<std::u16string> owned;
    std::vector<std::u16string_view> pieces;
    for (size_t i = 0; i < n; ++i) owned.push_back(Pool16(Below(kPoolSize)));
    for (auto& s : owned) pieces.push_back(s);

    std::u16string cat = base::StrCat(std::span<const std::u16string_view>(pieces));
    std::u16string dest = prefix;
    base::StrAppend(&dest, std::span<const std::u16string_view>(pieces));

    printf("    Case16 {\n        pieces: &[");
    for (auto& s : owned) printf("%s, ", U16Arr(s).c_str());
    printf("],\n        prefix: %s,\n", U16Arr(prefix).c_str());
    printf("        cat: %s,\n", U16Arr(cat).c_str());
    printf("        append: %s,\n    },\n", U16Arr(dest).c_str());
  }
  printf("];\n");
  // JoinStringT from join_string_internal.h, the template behind every
  // JoinString overload in string_util.h.
  printf("\npub struct JoinCase {\n    pub parts: &'static [&'static str],\n");
  printf("    pub sep: &'static str,\n    pub expected: &'static str,\n}\n\n");
  printf("pub const JOIN_CASES: &[JoinCase] = &[\n");
  const char* kSep8[] = {", ", "|", "", " ", "\xc3\xa9"};
  for (int c = 0; c < kCases; ++c) {
    size_t n = Below(6);
    std::string sep = kSep8[Below(5)];
    std::vector<std::string> owned;
    std::vector<std::string_view> parts;
    for (size_t i = 0; i < n; ++i) owned.push_back(kPool8[Below(kPoolSize)]);
    for (auto& s : owned) parts.push_back(s);
    std::string expected = base::strings_internal::JoinStringT<void>(
        parts, std::string_view(sep));
    printf("    JoinCase {\n        parts: &[");
    for (auto& s : owned) printf("%s, ", RustLit(s).c_str());
    printf("],\n        sep: %s,\n        expected: %s,\n    },\n",
           RustLit(sep).c_str(), RustLit(expected).c_str());
  }
  printf("];\n\n");

  const char16_t* kSep16[] = {u", ", u"|", u"", u" ", u"é"};
  printf("pub struct JoinCase16 {\n    pub parts: &'static [&'static [u16]],\n");
  printf("    pub sep: &'static [u16],\n    pub expected: &'static [u16],\n}\n\n");
  printf("pub const JOIN_CASES16: &[JoinCase16] = &[\n");
  for (int c = 0; c < kCases; ++c) {
    size_t n = Below(6);
    std::u16string sep = kSep16[Below(5)];
    std::vector<std::u16string> owned;
    std::vector<std::u16string_view> parts;
    for (size_t i = 0; i < n; ++i) owned.push_back(Pool16(Below(kPoolSize)));
    for (auto& s : owned) parts.push_back(s);
    std::u16string expected = base::strings_internal::JoinStringT<void>(
        parts, std::u16string_view(sep));
    printf("    JoinCase16 {\n        parts: &[");
    for (auto& s : owned) printf("%s, ", U16Arr(s).c_str());
    printf("],\n        sep: %s,\n        expected: %s,\n    },\n",
           U16Arr(sep).c_str(), U16Arr(expected).c_str());
  }
  printf("];\n");
  return 0;
}
