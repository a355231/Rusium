fn http_version_ordering_matches_cpp_transcript() {
    let mut count = 0;
    for line in VERSION_TRANSCRIPT.lines() {
        let fields: Vec<&str> = line.split(' ').collect();
        assert_eq!(fields.len(), 6, "{line}");
        let n: Vec<u16> = fields[..4].iter().map(|s| s.parse().unwrap()).collect();
        let a = HttpVersion::new(n[0], n[1]);
        let b = HttpVersion::new(n[2], n[3]);
        let expected_order = match fields[4] {
            "LT" => Ordering::Less,
            "EQ" => Ordering::Equal,
            "GT" => Ordering::Greater,
            other => panic!("bad order {other}"),
        };
        assert_eq!(a.cmp(&b), expected_order, "{line}");
        assert_eq!(a == b, fields[5] == "1", "{line}");
        count += 1;
    }
    assert!(count > 3000, "count: {count}");
}
